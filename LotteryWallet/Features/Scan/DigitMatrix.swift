import Foundation
import CoreGraphics

/// 配准后的号码矩阵：一注一行，每一格要么是一个号码，要么是问号。
///
/// 这是**格子路**的产物。格子的位置来自配准后的墨迹投影，和识别结果无关；
/// 每一个号码都答得出「你来自票面哪一格」，硬约束一就是这么落地的。
///
/// 以前还有一条「从识别结果里估几何」的路也产这个结构 —— 它已经删掉了。
/// 那条路的毛病是方向反的：认得越差，几何估得越偏；几何越偏，认得越错。
/// 更要命的是它**会盖住格子路的失败** —— 格子划不出来时它给出一个
/// 看起来差不多的答案，于是真正的问题在真机上连着几轮都看不出来。
struct DigitMatrix {

    /// 矩阵里的一注。
    struct Row {
        /// 这一行占的纵向区间（归一化，Vision 的 y 向上为正）。
        let band: ClosedRange<CGFloat>
        /// 每一位上的号码，认不出的是 nil（铺成文本时写作 `?`）。
        var values: [Int?]
    }

    let rows: [Row]
    /// 整个矩阵占的纵向区间。复原文本时这一段的原始行要整段换掉。
    let span: ClosedRange<CGFloat>
}
