import Foundation
import CoreGraphics

/// 号码矩阵的票面版式。
///
/// 里面**全是比值，没有一个像素数**。票在照片里占多大、用户裁得松还是紧、
/// 拍得远还是近，这些比值都不变 —— 这正是「裁切稍微不准就识别失败」的解药。
///
/// 数字是把真票逐像素量出来的（见 `Engineering/vision-rebuild.md` 第 3 节和第十四节）：
///
/// | | 列距 ÷ 字宽 | 分组 | 组间距 |
/// |---|---|---|---|
/// | 七星彩 | 3.62 | 6 + 1（特别号） | 1.58 列距 |
/// | 排列5 | 3.74 | 5 | — |
/// | 排列3 / 福彩3D | 3.43 / 2.65 | 3 | — |
/// | 大乐透 | 1.61 | 5 + 2（前区/后区） | 2.34 列距，中间印 `+` |
/// | 双色球 | 1.42 | 6 + 1（红/蓝） | 待实测 |
///
/// **分组是这张表的核心**。票面上的号码不是一路等距印到底的：
/// 七星彩的特别号离前六位远（1.58 个列距），大乐透的后区离前区更远（2.34），
/// 中间还印着一个 `+`。把「组内等距、组间隔一个已知的倍数」写成规则之后，
/// 这两件看着不一样的事其实是同一件事 —— 挑列的时候一条规则全覆盖。
struct DigitTicketLayout {

    /// 一组号码。票面上连续等距印的那一串。
    struct Group {
        /// 这一组印几个号码。
        let count: Int
        /// 这一组里每个号码的上限。七星彩的特别号是 0–14，大乐透后区 1–12。
        let maximum: Int
        /// 这一组的第一个号码，离**上一组最后一个**隔几个列距。
        ///
        /// 组内列距是 1，所以这个数只在组与组之间有意义；第一组写 0。
        let gap: CGFloat
    }

    let groups: [Group]

    /// 组与组之间**印不印分隔符**。
    ///
    /// 大乐透前后区之间印一个 `+`，双色球红蓝之间印 `-`。它们会在墨迹里
    /// 切出多余的一段，夹在号码中间 —— 挑列时要允许跳过，收行时要允许它
    /// 落在号码区里面而不算数。七星彩的特别号前面什么都不印，只是空得远。
    let separated: Bool

    /// 号码区右边**单独分出去的那一块**。没有就是 nil。
    ///
    /// 只有七星彩有：它的特别号离前六位远得多，而且是 0–14、印一位或两位。
    /// 前后试过三种把它塞进矩阵的办法（取并集、按字宽往左让、单格补认），
    /// 真机上五注里始终有三注读不出来 —— 而且每加一层特例都动了收行的前提，
    /// build 46 就是这么把整个格子路搞崩的。
    ///
    /// 分出去之后主矩阵回到规规矩矩的 6 列，**一个特例都没有**；
    /// 特别号那一块按界线切一条宽带，认出什么就拼什么。
    let trailing: Trailing?

    /// 那一块的描述。
    struct Trailing {
        /// 这一块里那个号码的上限。七星彩的特别号是 0–14。
        let maximum: Int
        /// 分界线落在主矩阵**最后一列中心**右边几个列距。
        ///
        /// 0.67 是拿 26042 那张真票量出来的（照片摆正 0.5°，605 宽裁图）：
        ///
        /// | | 像素 |
        /// |---|---|
        /// | 列距 | 64（5 个间隔量下来 64.5/64.5/64/64/63.5）|
        /// | 字宽 | 17.5（列距 ÷ 字宽 = 3.66，和文档 3.2 节的 3.62 对得上）|
        /// | 第6位右沿 | 487 |
        /// | 特别号十位左沿 | 556 |
        ///
        /// 中间那条空白带是 `[487, 556]`，宽 69px，**中点 521.5**，
        /// 相对第6位中心（478.5）是 43px = 0.67 个列距，
        /// 两边各留 34.5px ≈ **2 个字宽**的余量，对称。
        ///
        /// 还有一条帮忙的事实：特别号取值 0–14，所以**十位只可能是 `1`** ——
        /// 它的宽度是确定的（实测 9px 的细笔画），空白带的右界因此很稳。
        ///
        /// 列距是**这张票自己量出来的**（主矩阵 6 列一算就有），
        /// 所以拍远拍近、裁松裁紧都跟着变，只有 0.67 这个比值是版式常数。
        let divider: CGFloat
    }

    init(groups: [Group], separated: Bool = false, trailing: Trailing? = nil) {
        self.groups = groups
        self.separated = separated
        self.trailing = trailing
    }

    /// 一注一共几个号码，也就是号码矩阵有几列。
    var columns: Int { groups.reduce(0) { $0 + $1.count } }

    /// 每一列的上限，按组摊平。
    var maximums: [Int] {
        groups.flatMap { Array(repeating: $0.maximum, count: $0.count) }
    }

    /// 每一列离前一列隔几个列距。第一列没有前一列，所以有 `columns - 1` 个。
    ///
    /// 组内都是 1，组与组之间是那一组的 `gap`。挑列和补列都按这张表算。
    var pitches: [CGFloat] {
        var out: [CGFloat] = []
        for (index, group) in groups.enumerated() {
            if index > 0 { out.append(group.gap) }
            out.append(contentsOf: Array(repeating: 1, count: group.count - 1))
        }
        return out
    }


    /// 这个彩种的号码矩阵版式。不是矩阵排版的彩种就没有。
    ///
    /// 七乐彩、快乐8 印的是一长排两位数，Vision 横着读得好好的，
    /// 不该按矩阵去拆。
    static func of(_ game: GameKey) -> DigitTicketLayout? {
        switch game {
        case .fc3d, .pl3:
            DigitTicketLayout(groups: [Group(count: 3, maximum: 9, gap: 0)])
        case .pl5:
            DigitTicketLayout(groups: [Group(count: 5, maximum: 9, gap: 0)])
        case .qxc:
            // 前六位 0–9 是规规矩矩的矩阵；特别号 0–14 **不在矩阵里**，
            // 它单独分出去一块（见 `Trailing`）。
            DigitTicketLayout(groups: [Group(count: 6, maximum: 9, gap: 0)],
                              trailing: Trailing(maximum: 14, divider: 0.67))
        default:
            // 双色球、大乐透、七乐彩、快乐8 **不走矩阵路**，这是一条按
            // 「号码自不自带校验」划的界（文档第十六节）：
            //
            // | | 号码取值 | 自带校验 |
            // |---|---|---|
            // | 上面那四种数字型 | 0–9，任意数字都合法、可重复、无顺序 | 没有 |
            // | 双色球/大乐透/七乐彩/快乐8 | 两位数，升序、不重复、有值域 | **有** |
            //
            // 数字型彩种读错了没有任何办法发现（第七节第 5 条：票底流水号
            // `00084` 曾被读成一注），格子是它们唯一的护栏。
            // 而两位数那几种，一注号码自己就是一道校验 —— 解析器按升序、
            // 不重复、值域一卡，读错基本都会崩掉，再加一层格子是多余的。
            //
            // 大乐透的版式其实**是**矩阵（`+` 独立成段、号码间距 1.36 个字宽，
            // 实测值记在第十四节），真机上格子也划对了；但文本路本来就读得对，
            // 切过去只是多一条会出错的路。双色球更是反例：分隔符 `-` 和两边
            // 号码只隔 0.13 个字宽，墨迹投影只能把 `30-03` 连成一段，
            // 合并后一行 7 段正好等于 7 个号码 —— 段数对得上、内容全错。
            nil
        }
    }
}
